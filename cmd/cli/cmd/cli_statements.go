func processUsersWithProgressBar(ctx context.Context, fs *internal.FirestoreClient, users []*internal.User) error {
	const maxWorkers = 10 // Limit concurrent operations to avoid overwhelming Firestore
	
	// Create channels for work distribution
	userChan := make(chan *internal.User, len(users))
	resultsChan := make(chan UserProcessingResult, len(users))
	
	// Create progress bar
	bar := progressbar.NewOptions(len(users),
		progressbar.OptionSetDescription("Processing users"),
		progressbar.OptionSetWidth(50),
		progressbar.OptionShowCount(),
		progressbar.OptionShowIts(),
		progressbar.OptionSetItsString("users"),
		progressbar.OptionOnCompletion(func() {
			fmt.Println("\n")
		}),
	)
	
	// Start worker goroutines
	var wg sync.WaitGroup
	for i := 0; i < maxWorkers; i++ {
		wg.Add(1)
		go func() {
			defer wg.Done()
			for user := range userChan {
				result := processUserForInitialStatement(ctx, fs, user)
				resultsChan <- result
				bar.Add(1) // Update progress
			}
		}()
	}
	
	// Send work to workers
	go func() {
		defer close(userChan)
		for _, user := range users {
			userChan <- user
		}
	}()
	
	// Collect results
	go func() {
		wg.Wait()
		close(resultsChan)
	}()
	
	var results []UserProcessingResult
	for result := range resultsChan {
		results = append(results, result)
	}
	
	bar.Finish()
	
	// Process and display results
	return displayProcessingResults(results)
}

func processUserForInitialStatement(ctx context.Context, fs *internal.FirestoreClient, user *internal.User) UserProcessingResult {
	result := UserProcessingResult{
		UserID:    user.ID,
		UserEmail: user.Email,
		Success:   false,
	}
	
	// Find user's most recent completed appointment
	appointment, found, err := internal.GetLatestCompletedAppointment(ctx, fs, user.ID)
	if err != nil {
		result.Error = fmt.Errorf("failed to get latest completed appointment: %w", err)
		return result
	}
	if !found {
		result.Error = fmt.Errorf("no completed appointments found")
		return result
	}
	
	if appointment.CallID == nil {
		result.Error = fmt.Errorf("completed appointment %s has no call ID", appointment.ID)
		return result
	}
	
	// Get the transcript from the appointment
	transcript, err := internal.GetAppointmentTranscript(ctx, fs, *appointment.CallID)
	if err != nil {
		result.Error = fmt.Errorf("failed to get transcript for call %s: %w", *appointment.CallID, err)
		return result
	}
	
	if len(transcript.Messages) == 0 {
		result.Error = fmt.Errorf("transcript for call %s has no messages", *appointment.CallID)
		return result
	}
	
	// Create the initial statement version
	promptFile := "transcript.user-statement.v001.txt"
	version, err := internal.CreateInitialStatement(ctx, fs, user.ID, transcript, promptFile)
	if err != nil {
		result.Error = fmt.Errorf("failed to create initial statement: %w", err)
		return result
	}
	
	result.Success = true
	result.VersionID = version.ID
	return result
}

