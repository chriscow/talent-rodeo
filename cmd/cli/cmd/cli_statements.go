// Handler functions for regeneration

func handleSingleUserRegeneration(ctx context.Context, fs *internal.FirestoreClient) error {
	// Parse and validate version ID
	var targetVersionID string
	if versionID != "" {
		// Smart version parsing - add user prefix if missing
		if strings.Contains(versionID, "_v") {
			targetVersionID = versionID // Full version ID provided
		} else {
			// Just version part provided (e.g., "v4"), prepend user ID
			if strings.HasPrefix(versionID, "v") {
				targetVersionID = fmt.Sprintf("%s_%s", stmtUserID, versionID)
			} else {
				targetVersionID = fmt.Sprintf("%s_v%s", stmtUserID, versionID)
			}
		}
	} else {
		// No version specified - regenerate everything from beginning
		if !dryRun {
			fmt.Printf("⚠️  This will regenerate ALL statement versions for user %s from the beginning.\n", stmtUserID)
			fmt.Print("Are you sure you want to continue? (y/N): ")
			var response string
			fmt.Scanln(&response)
			if strings.ToLower(response) != "y" && strings.ToLower(response) != "yes" {
				fmt.Println("Operation cancelled.")
				return nil
			}
		}

		// Find the first version for this user
		versions, _, err := internal.GetStatementHistory(ctx, fs, stmtUserID, 1000, nil)
		if err != nil {
			return fmt.Errorf("failed to get statement history: %w", err)
		}
		if len(versions) == 0 {
			return fmt.Errorf("no statement versions found for user %s\n\nTo create statement versions from scratch:\n1. trcli statements create-initial --user %s\n2. trcli statements process-inbox --user %s\n3. trcli statements process-app-feedback --user %s\n4. trcli statements regenerate --user %s", stmtUserID, stmtUserID, stmtUserID, stmtUserID, stmtUserID)
		}

		// Get the first version (versions are returned in descending order, so take the last one)
		firstVersion := versions[len(versions)-1]
		targetVersionID = firstVersion.ID
	}

	if dryRun {
		fmt.Printf("DRY RUN: Would cascade regenerate from version %s\n", targetVersionID)
	} else {
		fmt.Printf("Cascade regenerating from version %s...\n", targetVersionID)
	}

	// Build dependency chain to show what will be affected
	dependencyChain, err := internal.BuildDependencyChain(ctx, fs, stmtUserID, targetVersionID)
	if err != nil {
		return fmt.Errorf("failed to build dependency chain: %w", err)
	}

	fmt.Printf("Dependency chain: %d versions will be affected\n", len(dependencyChain))
	for i, version := range dependencyChain {
		status := "→"
		if i == 0 {
			status = "🎯" // Target version
		}
		fmt.Printf("  %s %s (v%d, %s, %s)\n",
			status,
			version.ID,
			version.VersionNumber,
			version.GeneratedBy,
			version.PromptFile)
	}
	fmt.Println()

	// Create logger and registry for regeneration
	logger := slog.New(slog.NewTextHandler(os.Stderr, &slog.HandlerOptions{Level: slog.LevelInfo}))
	registry := createStatementRegeneratorRegistry(fs, logger)

	// Perform cascade regeneration
	report, err := internal.RegenerateCascade(ctx, fs, registry, targetVersionID, "", dryRun)
	if err != nil {
		return fmt.Errorf("failed to cascade regenerate: %w", err)
	}

	if jsonOutput {
		data, err := json.MarshalIndent(report, "", "  ")
		if err != nil {
			return fmt.Errorf("failed to marshal JSON: %w", err)
		}
		fmt.Println(string(data))
	} else {
		fmt.Printf("Cascade Regeneration Report\n")
		fmt.Println(strings.Repeat("=", 40))
		fmt.Printf("Operation ID: %s\n", report.Operation.ID)
		fmt.Printf("Status: %s\n", report.Operation.Status)
		fmt.Printf("Versions Processed: %d\n", report.VersionsProcessed)
		fmt.Printf("Successful: %d\n", report.VersionsSuccessful)
		fmt.Printf("Failed: %d\n", report.VersionsFailed)
		fmt.Printf("Duration: %s\n", report.Duration)
		fmt.Printf("Dry Run: %t\n", report.Operation.DryRun)

		if len(report.Operation.VersionsAffected) > 0 {
			fmt.Println("\nVersions Affected:")
			for _, versionID := range report.Operation.VersionsAffected {
				fmt.Printf("  - %s\n", versionID)
			}
		}

		fmt.Println("\nDetailed Results:")
		for _, result := range report.Results {
			statusIcon := "✅"
			if result.Status == "failed" {
				statusIcon = "❌"
			} else if result.Status == "would_regenerate" {
				statusIcon = "📋"
			}

			fmt.Printf("  %s %s (%s)\n", statusIcon, result.VersionID, result.Status)
			fmt.Printf("    System: %s, Prompt: %s\n", result.SystemType, result.PromptUsed)
			if result.NewVersionID != nil {
				fmt.Printf("    New Version: %s (%d chars)\n", *result.NewVersionID, result.StatementLength)
			}
			if result.Error != nil {
				fmt.Printf("    Error: %s\n", *result.Error)
			}
		}

		if !dryRun {
			fmt.Printf("\n✅ Cascade regeneration completed successfully!\n")
		}
	}

	return nil
}

func handleAllUsersRegeneration(ctx context.Context, fs *internal.FirestoreClient) error {
	// Create logger and registry for regeneration
	logger := slog.New(slog.NewTextHandler(os.Stderr, &slog.HandlerOptions{Level: slog.LevelInfo}))
	registry := createStatementRegeneratorRegistry(fs, logger)

	// Get all users with statements
	allUsers, err := internal.ListUsers(ctx, fs, 10000, 0) // Get up to 10k users
	if err != nil {
		return fmt.Errorf("failed to get all users: %w", err)
	}

	// Filter users who have statement versions
	var usersWithStatements []string
	for _, user := range allUsers {
		if user.CurrentStatementVersionID != nil {
			usersWithStatements = append(usersWithStatements, user.ID)
		}
	}

	if len(usersWithStatements) == 0 {
		fmt.Println("No users found with statement versions.")
		return nil
	}

	if !dryRun {
		fmt.Printf("⚠️  This will regenerate ALL statement versions for %d users from the beginning.\n", len(usersWithStatements))
		fmt.Print("Are you sure you want to continue? (y/N): ")
		var response string
		fmt.Scanln(&response)
		if strings.ToLower(response) != "y" && strings.ToLower(response) != "yes" {
			fmt.Println("Operation cancelled.")
			return nil
		}
	}

	fmt.Printf("Processing %d users with statement versions...\n", len(usersWithStatements))

	var totalProcessed, totalSuccessful, totalFailed int

	for i, userID := range usersWithStatements {
		fmt.Printf("\n[%d/%d] Processing user: %s\n", i+1, len(usersWithStatements), userID)

		// Find first version for this user
		versions, _, err := internal.GetStatementHistory(ctx, fs, userID, 1000, nil)
		if err != nil {
			fmt.Printf("  ❌ Failed to get versions for user %s: %v\n", userID, err)
			totalFailed++
			continue
		}

		if len(versions) == 0 {
			fmt.Printf("  ⚠️  No versions found for user %s\n", userID)
			continue
		}

		// Get the first version (last in descending order)
		firstVersion := versions[len(versions)-1]

		// Perform cascade regeneration for this user
		report, err := internal.RegenerateCascade(ctx, fs, registry, firstVersion.ID, "", dryRun)
		if err != nil {
			fmt.Printf("  ❌ Failed to regenerate for user %s: %v\n", userID, err)
			totalFailed++
		} else {
			fmt.Printf("  ✅ Regenerated %d versions for user %s\n", report.VersionsProcessed, userID)
			totalSuccessful++
		}
		totalProcessed++
	}

	// Summary
	fmt.Printf("\n🎯 All Users Regeneration Summary\n")
	fmt.Println(strings.Repeat("=", 40))
	fmt.Printf("Users Processed: %d\n", totalProcessed)
	fmt.Printf("Successful: %d\n", totalSuccessful)
	fmt.Printf("Failed: %d\n", totalFailed)
	fmt.Printf("Dry Run: %t\n", dryRun)

	if !dryRun && totalSuccessful > 0 {
		fmt.Printf("\n✅ All users regeneration completed!\n")
	}

	return nil
}

