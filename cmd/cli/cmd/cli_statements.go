// createStatementRegeneratorRegistry creates and configures a statement regenerator registry
// for use in CLI commands.
func createStatementRegeneratorRegistry(fs *internal.FirestoreClient, logger *slog.Logger) *internal.StatementGeneratorRegistry {
	registry := internal.NewStatementGeneratorRegistry(logger)

	// Register transcript system regenerator
	transcriptRegenerator := transcript.NewStatementGenerator(fs, logger)
	registry.Register("transcript", transcriptRegenerator)

	// Register feedback system regenerator
	feedbackStore := feedback.NewFeedbackStore(fs)
	feedbackLLMClient := feedback.NewMindsClient()
	feedbackRegenerator := feedback.NewStatementGenerator(feedbackStore, feedbackLLMClient, logger)
	registry.Register("feedback", feedbackRegenerator)

	return registry
}

