func handleProcessInbox(ctx context.Context, fs *internal.FirestoreClient) error {
	fmt.Printf("Processing inbox feedback for user %s...\n", stmtUserID)

	// Check if user has at least one statement version
	existing, err := internal.GetLatestStatement(ctx, fs, stmtUserID)
	if err != nil || existing == nil {
		return fmt.Errorf("user %s has no statement versions. Run create-initial first", stmtUserID)
	}

	// Get user details to find email address
	fmt.Printf("Retrieving user details for user %s...\n", stmtUserID)
	user, found, err := internal.GetUser(ctx, fs, stmtUserID)
	if err != nil {
		return fmt.Errorf("failed to get user: %w", err)
	}
	if !found {
		return fmt.Errorf("user %s not found", stmtUserID)
	}

	fmt.Printf("Found user: %s (%s)\n", user.Email, user.Name)

	// Get ALL emails from Gmail (both read and unread) for historical processing
	fmt.Printf("Retrieving ALL emails from Gmail for historical processing...\n")  
	
	logger := slog.New(slog.NewTextHandler(os.Stderr, &slog.HandlerOptions{Level: slog.LevelWarn}))
	config := inbox.InboxConfig{TokenPath: "gmail_token.json"}
	
	reader, err := inbox.NewGmailReader(config, logger)
	if err != nil {
		return fmt.Errorf("failed to create Gmail reader: %w", err)
	}
	defer reader.Close()
	
	// Get all emails (up to 50 for historical processing)
	emails, err := reader.GetAllEmails(ctx, 50)
	if err != nil {
		return fmt.Errorf("failed to get all emails: %w", err)
	}
	
	if len(emails) == 0 {
		fmt.Printf("✅ No emails found in Gmail\n")
		return nil
	}
	
	fmt.Printf("Retrieved %d total emails from Gmail\n", len(emails))
	
	// Filter emails to only process ones FROM the user (not TO the user)
	var userEmails []*inbox.Email
	for _, email := range emails {
		emailAddr := extractEmailAddressFromField(email.From)
		if emailAddr == user.Email {
			userEmails = append(userEmails, email)
		}
	}
	
	if len(userEmails) == 0 {
		fmt.Printf("✅ No emails found FROM user %s\n", user.Email)
		return nil
	}
	
	fmt.Printf("Found %d emails FROM user %s\n", len(userEmails), user.Email)
	
	// Sort emails chronologically (oldest first) for proper historical processing
	sort.Slice(userEmails, func(i, j int) bool {
		return userEmails[i].Date.Before(userEmails[j].Date)
	})
	
	if dryRun {
		fmt.Printf("DRY RUN: Would analyze %d emails from %s chronologically:\n", len(userEmails), user.Email)
		for i, email := range userEmails {
			fmt.Printf("  %d. %s: %s (%s)\n", 
				i+1, 
				email.Date.Format("2006-01-02 15:04"),
				truncateString(email.Subject, 60),
				truncateString(email.Body, 100))
		}
		return nil
	}
	
	// Set up LLM-based email analysis using the existing inbox feedback system
	openAIAPIKey := os.Getenv("OPENAI_API_KEY")
	if openAIAPIKey == "" {
		return fmt.Errorf("OPENAI_API_KEY environment variable is required for email analysis")
	}
	
	openAIClient := feedback.NewOpenAIClient(openAIAPIKey, logger)
	handler := feedback.NewInboxFeedbackHandler(openAIClient, fs, nil, "", logger)
	
	// Process each email chronologically using LLM analysis
	successCount := 0
	skippedCount := 0
	errorCount := 0
	
	fmt.Printf("Processing emails chronologically using LLM analysis...\n")
	
	for i, email := range userEmails {
		fmt.Printf("Processing email %d/%d: %s\n", 
			i+1, len(userEmails), 
			truncateString(email.Subject, 60))
		
		// Use the existing inbox feedback handler to process the email
		result, err := handler.HandleEmail(ctx, email)
		if err != nil {
			fmt.Printf("  ❌ Error processing email: %v\n", err)
			errorCount++
			continue
		}
		
		if result.Handled {
			fmt.Printf("  ✅ Search adjustment processed: %s\n", result.Summary)
			successCount++
		} else {
			fmt.Printf("  ⏭️  Skipped: Not a search adjustment request\n")
			skippedCount++
		}
	}
	
	fmt.Printf("\n📊 Processing Summary:\n")
	fmt.Printf("  Total emails analyzed: %d\n", len(userEmails))
	fmt.Printf("  Search adjustments processed: %d\n", successCount)
	fmt.Printf("  Non-adjustment emails skipped: %d\n", skippedCount)
	fmt.Printf("  Errors: %d\n", errorCount)
	
	if errorCount > 0 {
		return fmt.Errorf("processing completed with %d errors", errorCount)
	}
	
	fmt.Printf("✅ All inbox feedback processed successfully!\n")
	return nil
}

func handleProcessAppFeedback(ctx context.Context, fs *internal.FirestoreClient) error {
	fmt.Printf("Processing app-based feedback for user %s...\n", stmtUserID)

	// Check if user has at least one statement version
	existing, err := internal.GetLatestStatement(ctx, fs, stmtUserID)
	if err != nil || existing == nil {
		return fmt.Errorf("user %s has no statement versions. Run create-initial first", stmtUserID)
	}

	// Get ALL feedback records for this user (including previously processed)
	fmt.Printf("Querying for ALL feedback records for user %s...\n", stmtUserID)
	allFeedback, err := internal.ListUserFeedback(ctx, fs, stmtUserID)
	if err != nil {
		return fmt.Errorf("failed to get user feedback: %w", err)
	}

	if len(allFeedback) == 0 {
		fmt.Printf("✅ No feedback records found for user %s\n", stmtUserID)
		return nil
	}

	fmt.Printf("Found %d total feedback records (including previously processed)\n", len(allFeedback))

	if dryRun {
		fmt.Printf("DRY RUN: Would process %d feedback records for user %s:\n", len(allFeedback), stmtUserID)
		likedCount := 0
		dislikedCount := 0
		for i, feedback := range allFeedback {
			if feedback.Liked {
				likedCount++
			} else {
				dislikedCount++
			}
			if i < 10 { // Show first 10 examples
				likeStatus := "❤️"
				if !feedback.Liked {
					likeStatus = "👎"
				}
				fmt.Printf("  %d. %s %s: %s\n", 
					i+1, 
					likeStatus,
					feedback.CreatedAt.Format("2006-01-02"),
					truncateString(feedback.ItemText, 60))
			}
		}
		if len(allFeedback) > 10 {
			fmt.Printf("  ... and %d more\n", len(allFeedback)-10)
		}
		fmt.Printf("Summary: %d liked, %d disliked\n", likedCount, dislikedCount)
		return nil
	}

	// Group feedback chronologically to create statement versions
	// We'll process all feedback as a single batch to create an enhanced statement
	fmt.Printf("Processing all feedback through LLM-powered statement enhancement...\n")

	// Create feedback data structure for the enhanced statement system
	feedbackData := map[string]any{
		"source_type":     "app_feedback_batch",
		"total_feedback":  len(allFeedback),
		"feedback_items":  allFeedback,
		"processed_at":    time.Now().Format(time.RFC3339),
		"processing_mode": "bulk_reprocessing",
	}

	// Count liked vs disliked for summary
	likedCount := 0
	dislikedCount := 0
	for _, feedback := range allFeedback {
		if feedback.Liked {
			likedCount++
		} else {
			dislikedCount++
		}
	}

	feedbackData["liked_count"] = likedCount
	feedbackData["disliked_count"] = dislikedCount
	feedbackData["feedback_summary"] = fmt.Sprintf("%d liked, %d disliked items from job applications", likedCount, dislikedCount)

	fmt.Printf("Creating enhanced statement version from %d feedback items (%d ❤️, %d 👎)...\n", 
		len(allFeedback), likedCount, dislikedCount)

	// Use the feedback enhancement system to create a new statement version
	version, err := internal.EnhanceStatementWithAppFeedback(ctx, fs, stmtUserID, feedbackData, "statement-update.v001.txt")
	if err != nil {
		return fmt.Errorf("failed to create enhanced statement from feedback: %w", err)
	}

	fmt.Printf("✅ Successfully created enhanced statement version:\n")
	fmt.Printf("  - Version ID: %s\n", version.ID)
	fmt.Printf("  - Version Number: %d\n", version.VersionNumber)
	fmt.Printf("  - Generated By: %s\n", version.GeneratedBy)
	fmt.Printf("  - Statement Length: %d characters\n", len(version.StatementText))
	fmt.Printf("  - Based on: %d total feedback items\n", len(allFeedback))
	fmt.Printf("  - Statement Preview: %s...\n", truncateString(version.StatementText, 150))

	// Mark all feedback as processed since we've incorporated it into the statement
	feedbackIDs := make([]string, len(allFeedback))
	for i, feedback := range allFeedback {
		feedbackIDs[i] = feedback.ID
	}

	fmt.Printf("Marking %d feedback items as processed...\n", len(feedbackIDs))
	err = internal.MarkFeedbackAsProcessed(ctx, fs, feedbackIDs, time.Now())
	if err != nil {
		// Don't fail the entire operation if this fails, just warn
		fmt.Printf("⚠️  Warning: Failed to mark feedback as processed: %v\n", err)
	} else {
		fmt.Printf("✅ All feedback marked as processed\n")
	}

	fmt.Printf("✅ App-based feedback processing completed successfully!\n")
	return nil
}

func handleDeleteStatements(ctx context.Context, fs *internal.FirestoreClient) error {
	// Check if user exists first
	user, found, err := internal.GetUser(ctx, fs, stmtUserID)
	if err != nil {
		return fmt.Errorf("failed to get user: %w", err)
	}
	if !found {
		return fmt.Errorf("user %s not found", stmtUserID)
	}

	// Get current statement versions to show what will be deleted
	versions, _, err := internal.GetStatementHistory(ctx, fs, stmtUserID, 100, nil)
	if err != nil {
		return fmt.Errorf("failed to get statement history: %w", err)
	}

	if len(versions) == 0 {
		fmt.Printf("✅ No statement versions found for user %s (%s)\n", stmtUserID, user.Email)
		return nil
	}

	fmt.Printf("Found %d statement versions for user %s (%s):\n", len(versions), stmtUserID, user.Email)
	for _, version := range versions {
		fmt.Printf("  - %s (v%d, %s, %d chars, %s)\n", 
			version.ID, 
			version.VersionNumber,
			version.GeneratedBy,
			len(version.StatementText),
			version.CreatedAt.Format("2006-01-02 15:04"))
	}
	fmt.Println()

	// Get confirmation unless --force is used
	if !force {
		fmt.Printf("⚠️  WARNING: This will permanently delete ALL %d statement versions for user %s (%s).\n", 
			len(versions), stmtUserID, user.Email)
		fmt.Printf("This operation cannot be undone. The user's statement field will also be cleared.\n")
		fmt.Print("Are you sure you want to continue? (y/N): ")
		
		var response string
		fmt.Scanln(&response)
		if strings.ToLower(response) != "y" && strings.ToLower(response) != "yes" {
			fmt.Println("Operation cancelled.")
			return nil
		}
	}

	fmt.Printf("Deleting %d statement versions for user %s...\n", len(versions), stmtUserID)

	// Delete all statement versions
	deletedCount := 0
	errorCount := 0
	
	for _, version := range versions {
		_, err := fs.Collection("users").Doc(stmtUserID).Collection("user_statements").Doc(version.ID).Delete(ctx)
		if err != nil {
			fmt.Printf("  ❌ Failed to delete version %s: %v\n", version.ID, err)
			errorCount++
		} else {
			fmt.Printf("  ✅ Deleted version %s\n", version.ID)
			deletedCount++
		}
	}

	// Clear the user's current statement field and version reference
	fmt.Printf("Clearing user's current statement field...\n")
	updates := []firestore.Update{
		{Path: "statement", Value: firestore.Delete},
		{Path: "current_statement_version_id", Value: firestore.Delete},
	}
	_, err = fs.Collection("users").Doc(stmtUserID).Update(ctx, updates)
	if err != nil {
		fmt.Printf("⚠️  Warning: Failed to clear user statement field: %v\n", err)
	} else {
		fmt.Printf("✅ Cleared user statement field\n")
	}

	// Summary
	fmt.Printf("\n📊 Deletion Summary:\n")
	fmt.Printf("  Statement versions deleted: %d\n", deletedCount)
	fmt.Printf("  Deletion errors: %d\n", errorCount)
	fmt.Printf("  User statement field cleared: %t\n", err == nil)

	if errorCount > 0 {
		return fmt.Errorf("completed with %d deletion errors", errorCount)
	}

	fmt.Printf("\n✅ All statement versions deleted successfully for user %s!\n", stmtUserID)
	fmt.Printf("You can now run the statement generation commands to start fresh:\n")
	fmt.Printf("  1. trcli statements create-initial --user %s\n", stmtUserID)
	fmt.Printf("  2. trcli statements process-inbox --user %s\n", stmtUserID)
	fmt.Printf("  3. trcli statements process-app-feedback --user %s\n", stmtUserID)

	return nil
}

