// StatementGenerator handles updating user statements based on feedback analysis.
type StatementGenerator struct {
	store     FeedbackStore
	llmClient LLMClient
	logger    *slog.Logger
}

// NewStatementGenerator creates a new StatementGenerator.
func NewStatementGenerator(store FeedbackStore, llmClient LLMClient, logger *slog.Logger) *StatementGenerator {
	return &StatementGenerator{
		store:     store,
		llmClient: llmClient,
		logger:    logger.With("component", "feedback.StatementGenerator"),
	}
}

// Run processes feedback analysis to update a user statement.
func (sg *StatementGenerator) Run(ctx context.Context, currentStatement *string, analysis *SemanticFeedbackAnalysis) (string, error) {
	prompt, err := sg.buildPrompt(currentStatement, analysis)
	if err != nil {
		return "", fmt.Errorf("failed to build prompt: %w", err)
	}

	sg.logger.Debug("calling LLM to update statement", "prompt_length", len(prompt))

	updatedStatement, err := sg.llmClient.UpdateStatement(ctx, prompt)
	if err != nil {
		return "", fmt.Errorf("failed to update statement: %w", err)
	}

	// Clean up the statement (remove extra whitespace, ensure reasonable length)
	updatedStatement = strings.TrimSpace(updatedStatement)

	sg.logger.Debug("statement updated successfully",
		"original_length", getStatementLength(currentStatement),
		"updated_length", len(updatedStatement))

	return updatedStatement, nil
}

// buildPrompt constructs the prompt for the LLM to update the user statement.
func (sg *StatementGenerator) buildPrompt(currentStatement *string, analysis *SemanticFeedbackAnalysis) (string, error) {
	// Load the prompt template from embedded files
	promptBytes, err := assets.EmbeddedFiles.ReadFile("prompts/statement-update.v001.txt")
	if err != nil {
		return "", fmt.Errorf("failed to read statement update prompt template: %w", err)
	}

	promptTemplate := string(promptBytes)

	// Prepare current statement text
	currentStatementText := "No existing statement."
	if currentStatement != nil && *currentStatement != "" {
		currentStatementText = *currentStatement
	}

	// Build liked themes text
	likedThemesText := sg.buildThemesText(analysis.LikedThemes(), "LIKED")

	// Build disliked themes text
	dislikedThemesText := sg.buildThemesText(analysis.DislikedThemes(), "DISLIKED")

	// Replace placeholders in the template
	prompt := strings.ReplaceAll(promptTemplate, "{{.CURRENT_STATEMENT}}", currentStatementText)
	prompt = strings.ReplaceAll(prompt, "{{.LIKED_THEMES}}", likedThemesText)
	prompt = strings.ReplaceAll(prompt, "{{.DISLIKED_THEMES}}", dislikedThemesText)
	prompt = strings.ReplaceAll(prompt, "{{.CONFIDENCE_SCORE}}", fmt.Sprintf("%.2f", analysis.ConfidenceScore))
	prompt = strings.ReplaceAll(prompt, "{{.REASONING}}", analysis.Reasoning)

	return prompt, nil
}

// buildThemesText formats semantic themes for the prompt.
func (sg *StatementGenerator) buildThemesText(themes []SemanticTheme, preference string) string {
	if len(themes) == 0 {
		return fmt.Sprintf("No %s themes identified.", strings.ToLower(preference))
	}

	var parts []string
	for _, theme := range themes {
		keywords := strings.Join(theme.Keywords, ", ")
		parts = append(parts, fmt.Sprintf("- %s (keywords: %s)", theme.Theme, keywords))
	}

	return strings.Join(parts, "\n")
}

// getStatementLength safely gets the length of a statement pointer.
func getStatementLength(statement *string) int {
	if statement == nil {
		return 0
	}
	return len(*statement)
}

// GenerateStatement regenerates a statement using the feedback system's logic.
// It extracts the feedback analysis from the version's SourceData and re-runs
// the statement generation to create a new statement.
func (sg *StatementGenerator) GenerateStatement(ctx context.Context, version *internal.UserStatementVersion) (string, error) {
	sg.logger.Debug("regenerating statement from feedback version",
		"versionID", version.ID,
		"promptFile", version.PromptFile,
		"generatedBy", version.GeneratedBy)

	// Validate that this version was generated by the feedback system
	if version.GeneratedBy != "feedback" {
		return "", fmt.Errorf("version %s was not generated by feedback system (generatedBy: %s)", version.ID, version.GeneratedBy)
	}

	// Extract feedback analysis from source data
	analysis, err := sg.extractAnalysisFromSourceData(version.SourceData)
	if err != nil {
		return "", fmt.Errorf("failed to extract feedback analysis from source data: %w", err)
	}

	// Get user ID from version ID
	userID, err := sg.extractUserIDFromVersionID(version.ID)
	if err != nil {
		return "", fmt.Errorf("failed to extract user ID from version ID: %w", err)
	}

	// For cascade regeneration, we need to use the previous version's statement as the base,
	// not the current user statement (which might be corrupted or from a later version)
	var baseStatement *string
	if version.PreviousVersionID != nil {
		// Get the previous version to use its statement as the base
		previousVersion, err := sg.getPreviousVersion(ctx, userID, *version.PreviousVersionID)
		if err != nil {
			sg.logger.Warn("failed to get previous version for base statement", 
				"userID", userID, 
				"previousVersionID", *version.PreviousVersionID, 
				"error", err)
			// Fall back to current user statement
			baseStatement, _ = sg.store.GetUserStatement(ctx, userID)
		} else if previousVersion != nil {
			baseStatement = &previousVersion.StatementText
			sg.logger.Debug("using previous version as base statement",
				"previousVersionID", *version.PreviousVersionID,
				"baseStatementLength", len(previousVersion.StatementText))
		}
	} else {
		// No previous version, get current user statement
		baseStatement, _ = sg.store.GetUserStatement(ctx, userID)
	}

	if baseStatement == nil {
		sg.logger.Warn("no base statement available for regeneration", "userID", userID)
	}

	sg.logger.Debug("regenerating statement using StatementGenerator",
		"userID", userID,
		"hasBaseStatement", baseStatement != nil,
		"analysisConfidence", analysis.ConfidenceScore)

	// Use the statement generation logic to regenerate the statement
	// This ensures we use the exact same logic that was used originally
	regeneratedStatement, err := sg.Run(ctx, baseStatement, analysis)
	if err != nil {
		return "", fmt.Errorf("failed to regenerate statement: %w", err)
	}

	sg.logger.Debug("statement regenerated successfully",
		"originalVersionID", version.ID,
		"textLength", len(regeneratedStatement))

	return regeneratedStatement, nil
}

// extractAnalysisFromSourceData extracts the feedback analysis from the version's source data.
// Handles both application feedback (structured analysis) and inbox feedback (email-based).
func (sg *StatementGenerator) extractAnalysisFromSourceData(sourceData map[string]any) (*SemanticFeedbackAnalysis, error) {
	if sourceData == nil {
		return nil, fmt.Errorf("source data is nil")
	}

	// First, try to extract structured application feedback analysis
	if analysisData, exists := sourceData["feedback_analysis"]; exists {
		// Convert to analysis object
		analysis, ok := analysisData.(*SemanticFeedbackAnalysis)
		if !ok {
			return nil, fmt.Errorf("feedback_analysis data is not of expected type (got %T)", analysisData)
		}

		if analysis == nil {
			return nil, fmt.Errorf("feedback analysis is nil")
		}

		sg.logger.Debug("extracted structured application feedback analysis",
			"confidence_score", analysis.ConfidenceScore,
			"liked_themes_count", len(analysis.LikedThemes()),
			"disliked_themes_count", len(analysis.DislikedThemes()))

		return analysis, nil
	}

	// If no structured analysis, check for inbox feedback data
	if inboxData, exists := sourceData["inbox_feedback_data"]; exists {
		// Convert inbox feedback data to structured analysis format for compatibility
		analysis, err := sg.convertInboxDataToAnalysis(inboxData)
		if err != nil {
			return nil, fmt.Errorf("failed to convert inbox feedback data to analysis: %w", err)
		}

		sg.logger.Debug("converted inbox feedback data to structured analysis",
			"adjustment_request", analysis.Reasoning)

		return analysis, nil
	}

	// Check for legacy feedback_data format (used by older inbox processing)
	if feedbackData, exists := sourceData["feedback_data"]; exists {
		// Convert legacy feedback_data to structured analysis
		analysis, err := sg.convertInboxDataToAnalysis(feedbackData)
		if err != nil {
			return nil, fmt.Errorf("failed to convert legacy feedback_data to analysis: %w", err)
		}

		sg.logger.Debug("converted legacy feedback_data to structured analysis",
			"adjustment_request", analysis.Reasoning)

		return analysis, nil
	}

	// Check for legacy email feedback format (for backward compatibility)
	if emailContent, hasEmail := sourceData["email_content"]; hasEmail {
		if adjustmentRequest, hasAdjustment := sourceData["adjustment_request"]; hasAdjustment {
			// Convert legacy email feedback to structured analysis
			analysis := &SemanticFeedbackAnalysis{
				SemanticThemes: struct {
					Liked    []SemanticTheme `json:"Liked"`
					Disliked []SemanticTheme `json:"Disliked"`
				}{
					Liked:    []SemanticTheme{},
					Disliked: []SemanticTheme{},
				},
				ConfidenceScore:  1.0, // High confidence for explicit user requests
				TrendingPatterns: fmt.Sprintf("User requested: %v", adjustmentRequest),
				Reasoning:        fmt.Sprintf("Email-based feedback: %v", adjustmentRequest),
			}

			sg.logger.Debug("converted legacy email feedback data to structured analysis",
				"email_content_length", len(fmt.Sprintf("%v", emailContent)),
				"adjustment_request", adjustmentRequest)

			return analysis, nil
		}
	}

	return nil, fmt.Errorf("no supported feedback data found in source data (expected 'feedback_analysis', 'inbox_feedback_data', or 'email_content' + 'adjustment_request')")
}

// convertInboxDataToAnalysis converts inbox feedback data to SemanticFeedbackAnalysis format
func (sg *StatementGenerator) convertInboxDataToAnalysis(inboxDataRaw any) (*SemanticFeedbackAnalysis, error) {
	inboxDataMap, ok := inboxDataRaw.(map[string]any)
	if !ok {
		return nil, fmt.Errorf("inbox_feedback_data is not a map (got %T)", inboxDataRaw)
	}

	// Extract adjustment request which contains the user's intent
	adjustmentRequest, _ := inboxDataMap["adjustment_request"].(string)
	emailContent, _ := inboxDataMap["email_content"].(string)

	// Create a structured analysis that represents the user's email request
	// This allows the existing statement generation logic to work with inbox data
	analysis := &SemanticFeedbackAnalysis{
		SemanticThemes: struct {
			Liked    []SemanticTheme `json:"Liked"`
			Disliked []SemanticTheme `json:"Disliked"`
		}{
			Liked:    []SemanticTheme{}, // Email feedback doesn't have liked/disliked themes initially
			Disliked: []SemanticTheme{},
		},
		ConfidenceScore:  1.0, // High confidence since this is explicit user communication
		TrendingPatterns: fmt.Sprintf("Email request: %s", adjustmentRequest),
		Reasoning:        fmt.Sprintf("User email feedback - Adjustment: %s", adjustmentRequest),
	}

	// Try to infer themes from the adjustment request
	if adjustmentRequest != "" {
		// Create a synthetic theme from the user's request
		theme := SemanticTheme{
			Theme:           adjustmentRequest,
			Keywords:        []string{}, // We don't extract keywords from inbox feedback
			ConfidenceScore: 1.0,
			Frequency:       1,
		}

		// Determine if this is something to avoid or prefer based on common patterns
		adjustmentLower := strings.ToLower(adjustmentRequest)
		if strings.Contains(adjustmentLower, "no ") || 
		   strings.Contains(adjustmentLower, "avoid") || 
		   strings.Contains(adjustmentLower, "exclude") || 
		   strings.Contains(adjustmentLower, "don't want") {
			analysis.SemanticThemes.Disliked = append(analysis.SemanticThemes.Disliked, theme)
		} else {
			analysis.SemanticThemes.Liked = append(analysis.SemanticThemes.Liked, theme)
		}
	}

	sg.logger.Debug("converted inbox feedback to analysis",
		"adjustment_request", adjustmentRequest,
		"email_content_length", len(emailContent),
		"liked_themes", len(analysis.LikedThemes()),
		"disliked_themes", len(analysis.DislikedThemes()))

	return analysis, nil
}

// getPreviousVersion retrieves a specific version by ID for cascade regeneration
func (sg *StatementGenerator) getPreviousVersion(ctx context.Context, userID, versionID string) (*internal.UserStatementVersion, error) {
	// Access the Firestore client directly to get the specific version
	firestoreStore, ok := sg.store.(*firestoreStore)
	if !ok {
		return nil, fmt.Errorf("store is not a firestoreStore")
	}

	// Get the specific version document
	versionRef := firestoreStore.fs.Collection("users").Doc(userID).Collection("user_statements").Doc(versionID)
	doc, err := versionRef.Get(ctx)
	if err != nil {
		return nil, fmt.Errorf("failed to get version %s: %w", versionID, err)
	}

	var version internal.UserStatementVersion
	if err := doc.DataTo(&version); err != nil {
		return nil, fmt.Errorf("failed to unmarshal version %s: %w", versionID, err)
	}

	return &version, nil
}

// extractUserIDFromVersionID extracts the user ID from a version ID.
// Version IDs follow the format: {userID}_v{versionNumber}
func (sg *StatementGenerator) extractUserIDFromVersionID(versionID string) (string, error) {
	// Find the last occurrence of "_v" to split userID from version
	lastIndex := -1
	for i := len(versionID) - 1; i >= 0; i-- {
		if i > 0 && versionID[i-1:i+1] == "_v" {
			lastIndex = i - 1
			break
		}
	}

	if lastIndex == -1 {
		return "", fmt.Errorf("version ID %s does not follow expected format: {userID}_v{number}", versionID)
	}

	userID := versionID[:lastIndex]
	if userID == "" {
		return "", fmt.Errorf("extracted empty user ID from version ID: %s", versionID)
	}

	return userID, nil
}
