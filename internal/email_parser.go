// EmailRequest represents a single actionable request extracted from an email.
// It maintains referential integrity by preserving the exact quote from the original email.
type EmailRequest struct {
	// ID is a unique identifier for this request within the email
	ID string
	// Type categorizes the request (e.g., "job_search", "account", "feedback")
	Type string
	// Description is the LLM's interpretation of what the request is asking for
	Description string
	// Quote is the exact text from the original email that contains this request
	Quote string
	// Handled indicates whether a handler has processed this request
	Handled bool
	// HandlerID identifies which handler processed this request (empty if unhandled)
	HandlerID string
	// Response contains context from the handler for response generation
	Response string
}

// EmailStructure represents the parsed structure of an email with categorized content.
// This structure is generated by LLM analysis to separate actionable requests from other content.
type EmailStructure struct {
	// Requests contains actionable items that handlers can process
	Requests []EmailRequest
	// GeneralFeedback contains human feedback that should be escalated to admin
	GeneralFeedback []EmailRequest
	// NonRequests contains non-actionable content (greetings, signatures, etc.)
	NonRequests []EmailRequest
}

// EmailParser defines the interface for converting raw emails into structured format.
// Implementations use LLM analysis to extract and categorize email content.
type EmailParser interface {
	// ParseEmail analyzes an email and returns its structured representation.
	// Returns an error if parsing fails or if the email cannot be processed.
	ParseEmail(ctx context.Context, email *inbox.Email) (*EmailStructure, error)
}

// openAIEmailParser implements EmailParser using the OpenAI API with cost tracking.
type openAIEmailParser struct {
	client *openai.Client
	logger *slog.Logger
	fs     *FirestoreClient
}

// NewOpenAIEmailParser creates a new OpenAI-based email parser instance with cost tracking.
func NewOpenAIEmailParser(apiKey string, logger *slog.Logger, fs *FirestoreClient) EmailParser {
	return &openAIEmailParser{
		client: openai.NewClient(apiKey),
		logger: logger,
		fs:     fs,
	}
}

// ParseEmail analyzes an email and returns its structured representation with cost tracking.
func (p *openAIEmailParser) ParseEmail(ctx context.Context, email *inbox.Email) (*EmailStructure, error) {
	if email == nil {
		return nil, fmt.Errorf("email cannot be nil")
	}

	if strings.TrimSpace(email.Body) == "" {
		return &EmailStructure{
			Requests:        []EmailRequest{},
			GeneralFeedback: []EmailRequest{},
			NonRequests:     []EmailRequest{},
		}, nil
	}

	prompt := p.buildParsingPrompt(email)

	var resp openai.ChatCompletionResponse
	structure, err := tools.StructuredAsk[EmailStructure](ctx, prompt,
		tools.WantCompletionResponse(&resp),
		tools.WithMaxTokens(8192),
		tools.WithModel(tools.GPT41),
	)
	if err != nil {
		p.logger.Error("failed to parse email", "error", err, "email_id", email.ID)
		return nil, fmt.Errorf("failed to parse email: %w", err)
	}

	p.assignRequestIDs(&structure)

	// Record cost tracking - look up user by email
	user, found, err := GetUserByEmail(ctx, p.fs, email.From)
	if err != nil {
		p.logger.Warn("failed to get user for cost tracking", "error", err, "email", email.From)
		// Don't fail parsing just because cost tracking failed
	} else if found {
		// Record LLM cost for the user
		if err := RecordLLMCost(ctx, p.fs, &user.ID, string(tools.GPT41), resp, "email_parsing", nil); err != nil {
			p.logger.Error("failed to record LLM cost", "error", err, "user_id", user.ID, "email_id", email.ID)
			// Don't fail parsing just because cost tracking failed
		}
	} else {
		p.logger.Debug("user not found for cost tracking", "email", email.From, "email_id", email.ID)
	}

	return &structure, nil
}

// buildParsingPrompt creates the OpenAI prompt for email parsing
func (p *openAIEmailParser) buildParsingPrompt(email *inbox.Email) string {
	return fmt.Sprintf(`You are an AI assistant tasked with analyzing and categorizing the content of an email. Your goal is to extract actionable requests, general feedback, and non-actionable content from the email, and present this information in a structured JSON format.

Here are the details of the email you need to analyze:

<email>
From: %s
Subject: %s
Body: %s
</email>

Your task is to parse the email content and categorize it into three types:

1. REQUESTS: Actionable items that can be automated (job search changes, account updates, etc.)
2. GENERAL_FEEDBACK: Human feedback, complaints, or comments that need admin review
3. NON_REQUESTS: Greetings, signatures, pleasantries, or non-actionable content

For each item you identify, you need to provide:
- type: The category (e.g., job_search, account, feedback, etc.)
- description: A brief explanation of what the request or feedback is about
- quote: The EXACT text from the email that corresponds to this item

Follow these steps to analyze and categorize the email content:

1. Read through the entire email carefully.
2. Identify any actionable requests and categorize them as REQUESTS.
3. Look for feedback, complaints, or comments that require human review and categorize them as GENERAL_FEEDBACK.
4. Categorize greetings, signatures, and other non-actionable content as NON_REQUESTS.
5. For each item, determine the appropriate type, write a concise description, and extract the exact quote from the email.

Examples of how to handle different types of content:

- If the email says "I would like to change my job search preferences to include remote work," categorize this as a REQUEST with type "job_search".
- If the email contains "Your service has been great, but the job recommendations could be more accurate," categorize this as GENERAL_FEEDBACK with type "feedback".
- If the email starts with "Dear Support Team," categorize this as a NON_REQUEST with type "greeting".

After analyzing the email, present your findings in the following JSON format:

{
  "requests": [
    {
      "type": "job_search",
      "description": "User wants to add remote work preference",
      "quote": "I would like to work remotely"
    }
  ],
  "general_feedback": [
    {
      "type": "feedback",
      "description": "User feedback about the service",
      "quote": "The job recommendations could be better"
    }
  ],
  "non_requests": [
    {
      "type": "greeting",
      "description": "Email greeting",
      "quote": "Hi there"
    }
  ]
}

It is crucial that you output ONLY valid JSON in this format. Do not include any additional text or explanations outside of the JSON structure.

Before providing your final answer, use a <scratchpad> to think through the categorization process and organize your thoughts. In your scratchpad, you can list out the items you've identified and how you plan to categorize them.

Your final output should consist of only the JSON structure containing the categorized email content. Do not include the scratchpad or any other text in your final answer.`, email.From, email.Subject, email.Body)
}

// assignRequestIDs assigns unique IDs to all requests in the structure
func (p *openAIEmailParser) assignRequestIDs(structure *EmailStructure) {
	counter := 1

	for i := range structure.Requests {
		structure.Requests[i].ID = fmt.Sprintf("req_%d", counter)
		counter++
	}

	for i := range structure.GeneralFeedback {
		structure.GeneralFeedback[i].ID = fmt.Sprintf("feedback_%d", counter)
		counter++
	}

	for i := range structure.NonRequests {
		structure.NonRequests[i].ID = fmt.Sprintf("non_req_%d", counter)
		counter++
	}
}