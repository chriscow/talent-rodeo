package transcript

import (
	"context"
	"fmt"
	"log/slog"

	"talent-rodeo/internal"
)

// StatementGenerator implements the internal.StatementGenerator interface
// for the transcript system. It handles regenerating user statements from
// transcript data using the original prompt file.
type StatementGenerator struct {
	fs     *internal.FirestoreClient
	logger *slog.Logger
}

// NewStatementGenerator creates a new transcript statement regenerator.
func NewStatementGenerator(fs *internal.FirestoreClient, logger *slog.Logger) *StatementGenerator {
	return &StatementGenerator{
		fs:     fs,
		logger: logger.With("component", "transcript.StatementRegenerator"),
	}
}

// GenerateStatement regenerates a statement using the transcript system's logic.
// It extracts the transcript data from the version's SourceData and uses the
// same prompt file that was originally used to generate the statement.
func (r *StatementGenerator) GenerateStatement(ctx context.Context, version *internal.UserStatementVersion) (string, error) {
	r.logger.Debug("regenerating statement from transcript version",
		"versionID", version.ID,
		"promptFile", version.PromptFile,
		"generatedBy", version.GeneratedBy)

	// Validate that this version was generated by the transcript system
	if version.GeneratedBy != "transcript" {
		return "", fmt.Errorf("version %s was not generated by transcript system (generatedBy: %s)", version.ID, version.GeneratedBy)
	}

	// Extract transcript from source data
	transcript, err := r.extractTranscriptFromSourceData(version.SourceData)
	if err != nil {
		return "", fmt.Errorf("failed to extract transcript from source data: %w", err)
	}

	// Get user ID from version ID (format: userID_v{number})
	userID, err := r.extractUserIDFromVersionID(version.ID)
	if err != nil {
		return "", fmt.Errorf("failed to extract user ID from version ID: %w", err)
	}

	r.logger.Debug("regenerating statement using CreateInitialStatement",
		"userID", userID,
		"promptFile", version.PromptFile)

	// Use the existing CreateInitialStatement function with the same prompt file
	// This ensures we use the exact same logic that was used originally
	regeneratedVersion, err := internal.CreateInitialStatement(ctx, r.fs, userID, transcript, version.PromptFile)
	if err != nil {
		return "", fmt.Errorf("failed to regenerate statement: %w", err)
	}

	r.logger.Debug("statement regenerated successfully",
		"originalVersionID", version.ID,
		"regeneratedVersionID", regeneratedVersion.ID,
		"textLength", len(regeneratedVersion.StatementText))

	return regeneratedVersion.StatementText, nil
}

// extractTranscriptFromSourceData extracts the transcript from the version's source data.
func (r *StatementGenerator) extractTranscriptFromSourceData(sourceData map[string]any) (*internal.Transcript, error) {
	if sourceData == nil {
		return nil, fmt.Errorf("source data is nil")
	}

	// Try to extract transcript data
	transcriptData, exists := sourceData["transcript"]
	if !exists {
		return nil, fmt.Errorf("transcript data not found in source data")
	}

	// Convert to transcript object
	// This assumes the transcript was stored as a serialized structure
	transcript, ok := transcriptData.(*internal.Transcript)
	if !ok {
		return nil, fmt.Errorf("transcript data is not of expected type (got %T)", transcriptData)
	}

	if transcript == nil {
		return nil, fmt.Errorf("transcript is nil")
	}

	return transcript, nil
}

// extractUserIDFromVersionID extracts the user ID from a version ID.
// Version IDs follow the format: {userID}_v{versionNumber}
func (r *StatementGenerator) extractUserIDFromVersionID(versionID string) (string, error) {
	// Find the last occurrence of "_v" to split userID from version
	lastIndex := -1
	for i := len(versionID) - 1; i >= 0; i-- {
		if i > 0 && versionID[i-1:i+1] == "_v" {
			lastIndex = i - 1
			break
		}
	}

	if lastIndex == -1 {
		return "", fmt.Errorf("version ID %s does not follow expected format: {userID}_v{number}", versionID)
	}

	userID := versionID[:lastIndex]
	if userID == "" {
		return "", fmt.Errorf("extracted empty user ID from version ID: %s", versionID)
	}

	return userID, nil
}
